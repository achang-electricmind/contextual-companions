#!/usr/bin/env python3
"""Preview or safely merge a canonical CCS companion into a target repository.

Default mode is dry-run; --apply is explicit and never overwrites edited skill files.
"""
import argparse
from difflib import unified_diff
from pathlib import Path
import sys
import re
from ccs import HOSTS, Invalid, ROOT, cue_block, host_spec, runtime_files, validate, START, END


def check_parents(target: Path, path: Path):
    if target.is_symlink() or not target.is_dir():
        raise Invalid('target root changed or is not a real directory')
    try:
        relative = path.relative_to(target)
    except ValueError as exc:
        raise Invalid(f'destination escapes repository: {path}') from exc
    current = target
    for part in relative.parts:
        current = current / part
        if current.is_symlink():
            raise Invalid(f'symlink in target destination: {current}')


def merge_cue(original: str, block: str, companion: str) -> str:
    start = START.format(id=companion)
    end = END.format(id=companion)
    begins = original.count(start)
    ends = original.count(end)
    if begins != ends or begins > 1:
        raise Invalid('malformed, duplicated or unmatched companion cue markers; review manually')
    if begins == 1 and original.index(start) > original.index(end):
        raise Invalid('reversed companion cue markers; review manually')
    if begins == 1:
        before, rest = original.split(start, 1)
        _, after = rest.split(end, 1)
        if after.startswith('\n'):
            after = after[1:]
        return before + block + after
    if original and not original.endswith('\n'):
        original += '\n'
    return original + ('\n' if original else '') + block


def plan_install(target: Path, host: str, companion: str) -> dict:
    if not target.is_dir() or target.is_symlink():
        raise Invalid('target must be an existing real directory')
    target = target.resolve()
    if target == Path('/') or target == Path.home().resolve():
        raise Invalid('target must be a specific course/project repository, not / or home')
    if target == ROOT or target.is_relative_to(ROOT):
        raise Invalid('do not install into the source kit')
    validate(companion)
    paths = runtime_files(companion, host)
    to_create = {}
    expected = {}
    for relative, content in sorted(paths.items()):
        destination = target / relative
        check_parents(target, destination)
        expected[destination] = destination.read_bytes() if destination.is_file() else None
        if destination.exists():
            if not destination.is_file() or destination.read_bytes() != content:
                raise Invalid(f'existing skill file differs; refused overwrite: {destination}')
        else:
            to_create[destination] = content
    instructions = target / host_spec(host)['instruction_file']
    check_parents(target, instructions)
    if instructions.exists() and not instructions.is_file():
        raise Invalid(f'instruction target is not a file: {instructions}')
    expected[instructions] = instructions.read_bytes() if instructions.exists() else None
    before = expected[instructions].decode('utf-8') if expected[instructions] is not None else ''
    if re.search(r'(?im)^.*(?:do not edit|generated by|managed by|aide[-_ :]+managed|begin aide).*$', before):
        raise Invalid('instruction file appears managed; use the project-approved customization location manually')
    after = merge_cue(before, cue_block(companion, host), companion)
    return {
        'target': target,
        'create': to_create,
        'instructions': instructions,
        'before': before,
        'after': after,
        'expected': expected,
    }


def write_plan(plan: dict):
    # Refuse stale plans before creating any skill file. This is a local preflight,
    # not a filesystem lock against simultaneous edits during the write itself.
    for path, expected in plan['expected'].items():
        check_parents(plan['target'], path)
        if expected is None:
            if path.exists():
                raise Invalid('installation target changed after planning; preview again')
        elif not path.is_file() or path.read_bytes() != expected:
            raise Invalid('installation target changed after planning; preview again')
    for path, content in plan['create'].items():
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open('xb') as file:
            file.write(content)
    instruction = plan['instructions']
    if plan['before'] != plan['after']:
        instruction.parent.mkdir(parents=True, exist_ok=True)
        if instruction.exists():
            # Rewrite only after preflight, preserving the original file mode.
            import os
            import tempfile
            descriptor, name = tempfile.mkstemp(prefix='.ccs-', dir=instruction.parent)
            try:
                with os.fdopen(descriptor, 'w', encoding='utf-8', newline='\n') as file:
                    file.write(plan['after'])
                os.chmod(name, instruction.stat().st_mode & 0o777)
                os.replace(name, instruction)
            finally:
                if os.path.exists(name):
                    os.unlink(name)
        else:
            with instruction.open('x', encoding='utf-8') as file:
                file.write(plan['after'])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--host', choices=HOSTS, required=True)
    parser.add_argument('--target', type=Path, required=True)
    parser.add_argument('--companion', default='git-companion')
    parser.add_argument('--apply', action='store_true', help='perform the planned additive file changes')
    args = parser.parse_args()
    plan = plan_install(args.target, args.host, args.companion)
    mode = 'APPLY' if args.apply else 'PREVIEW (no writes)'
    print(f'{mode}: {args.companion} -> {args.host} | {plan["target"]}')
    print(f'New skill files: {len(plan["create"])}')
    for path in plan['create']:
        print(f' + {path.relative_to(plan["target"])}')
    if plan['before'] != plan['after']:
        print(f'Instruction cue change: {plan["instructions"].relative_to(plan["target"])}')
        print(''.join(unified_diff(plan['before'].splitlines(keepends=True), plan['after'].splitlines(keepends=True), fromfile='before', tofile='after')))
    else:
        print('Instruction cue already matches; no change.')
    if args.apply:
        write_plan(plan)
        print('INSTALLED. Review the repository diff and verify in the selected host.')
    else:
        print('NOT INSTALLED. Re-run with --apply after reviewing this plan.')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError, UnicodeError) as exc:
        print(f'Installation refused: {exc}', file=sys.stderr)
        sys.exit(1)
